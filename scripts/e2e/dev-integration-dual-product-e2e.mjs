// Evidence-pinned, not a standing guard. Synthetic-only verifier run once against one stack:
// platform-core (Carelog auth + Finance reference signup/login, DEV dual-auth) behind gateway-app, the REAL
// carelog-be (prod profile), and finance-harness-be. Every account is created through the Gateway.
// Only statuses, booleans, counts and fixed messages are printed; tokens, passwords, emails, names and
// account/user/journal ids are never logged.

import { execFileSync } from 'node:child_process';
import { strict as assert } from 'node:assert';
import { randomBytes, randomUUID } from 'node:crypto';
import { appendFile, readdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const ENROLLMENT_PATH_PREFIX = '/api/v1/internal/v1/identity/carelog/enrollments/';
const CLAIMS_PATH_PREFIX = '/api/v1/internal/identity/claims/';
const FINANCE_ISSUER = 'urn:ranikunlabs:identity:finance:reference';
const ACCESS_LINE = /^(\S+) (\S+) (\d{3}) cl=(\S*) te=(.*)$/;

let stage = 'initialization';
const observed = {};

async function send(method, url, { headers = {}, body } = {}) {
  const init = { method, headers: { accept: 'application/json', ...headers } };
  if (body !== undefined) {
    init.headers['content-type'] = 'application/json';
    init.body = JSON.stringify(body);
  }
  const response = await fetch(url, init);
  const text = await response.text();
  let json = null;
  try {
    json = text ? JSON.parse(text) : null;
  } catch {
    json = null;
  }
  return { status: response.status, headers: response.headers, json };
}

function expectStatus(result, expected, label) {
  if (result.status !== expected) {
    // Server messages are fixed Core/Gateway/Finance strings; they separate a Gateway 503 from a Core 503.
    const message = typeof result.json?.message === 'string' && result.json.message.length <= 120
      ? ` message="${result.json.message}"`
      : '';
    stage = `${label} HTTP ${result.status}${message}`;
    assert.fail(`${label}: expected ${expected}, got ${result.status}`);
  }
  stage = label;
}

function jwtClaims(token) {
  const parts = token.split('.');
  assert.equal(parts.length, 3);
  return JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
}

// Read-only SQL. Interpolated values are UUIDs or synthetic values generated by this script.
function psql(database, sql) {
  let out;
  try {
    out = execFileSync(
      'psql',
      [
        '-h', process.env.PGHOST ?? '127.0.0.1',
        '-p', process.env.PGPORT ?? '5432',
        '-U', process.env.PGUSER ?? 'postgres',
        '-d', database,
        '-At', '-F', '\t',
        '-v', 'ON_ERROR_STOP=1',
        '-c', sql,
      ],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] },
    ).trim();
  } catch {
    // Do not surface the command line: it carries synthetic account and login values.
    throw new Error(`psql query failed on ${database} (details withheld)`);
  }
  return out === '' ? [] : out.split('\n').map((line) => line.split('\t'));
}

async function readAccessLog() {
  const dir = process.env.E2E_CARELOG_ACCESS_LOG_DIR;
  assert.ok(dir, 'E2E_CARELOG_ACCESS_LOG_DIR is required');
  const names = (await readdir(dir)).filter((name) => name.startsWith('access_log'));
  const rows = [];
  for (const name of names) {
    const text = await readFile(join(dir, name), 'utf8');
    for (const line of text.split('\n')) {
      const match = ACCESS_LINE.exec(line.trim());
      if (match) {
        rows.push({ method: match[1], path: match[2], status: Number(match[3]), cl: match[4], te: match[5] });
      }
    }
  }
  return rows;
}

// carelog-be writes its access-log line after the response is sent: re-read for up to 3s until the condition holds.
async function waitForAccessLog(predicate, windowMs = 3000) {
  const deadline = Date.now() + windowMs;
  let rows = await readAccessLog();
  while (!predicate(rows) && Date.now() < deadline) {
    await new Promise((resolve) => setTimeout(resolve, 250));
    rows = await readAccessLog();
  }
  return rows;
}

const putsFor = (rows, accountId) =>
  rows.filter((r) => r.method === 'PUT' && r.path === `${ENROLLMENT_PATH_PREFIX}${accountId}`);
const claimsOkFor = (rows, accountId) =>
  rows.filter((r) => r.method === 'GET' && r.path === `${CLAIMS_PATH_PREFIX}${accountId}` && r.status === 200);

async function carelogSection(base) {
  const runId = randomBytes(6).toString('hex');
  const carelog = {
    userId: `dual-carelog-${runId}`,
    email: `dual-carelog-${runId}@example.test`,
    password: 'CarelogDual-pass1',
    name: 'Synthetic Carelog Manager',
  };
  const idempotencyKey = randomUUID();

  stage = 'Carelog registration through Gateway';
  const registration = await send('POST', `${base}/api/v1/auth/carelog/registration`, {
    headers: { 'idempotency-key': idempotencyKey },
    body: carelog,
  });
  expectStatus(registration, 201, 'Carelog registration through Gateway');
  observed.carelogRegistration = registration.status;

  stage = 'Core registration operation row';
  const operation = psql('platform_e2e',
    `SELECT account_id, state FROM identity.carelog_registration_operation WHERE operation_key = '${idempotencyKey}'`);
  assert.equal(operation.length, 1, 'exactly one Core operation row for the key');
  const [accountId, operationState] = operation[0];
  assert.match(accountId, UUID_RE);
  assert.equal(operationState, 'COMPLETED');
  observed.coreOperationState = operationState;

  stage = 'Core credential row';
  const credential = psql('platform_e2e',
    `SELECT account_id FROM identity.password_credentials WHERE login_id = '${carelog.userId}'`);
  assert.equal(credential.length, 1, 'exactly one Core credential row for the login id');
  assert.equal(credential[0][0], accountId, 'credential account must match operation account');

  stage = 'carelog-be enrollment row';
  const users = psql('carelog_be_e2e',
    `SELECT count(*) FROM users WHERE external_account_id = '${accountId}' AND role = 'MANAGER'`);
  observed.carelogUserRows = Number(users[0][0]);
  assert.equal(observed.carelogUserRows, 1, 'carelog-be must hold exactly one MANAGER row for the accountId');

  // Enrollment PUT: exactly one, answered 201 by the real carelog-be, arriving chunked from Core's JDK client.
  stage = 'carelog-be access log: enrollment PUT';
  let rows = await waitForAccessLog((r) => putsFor(r, accountId).length >= 1);
  const puts = putsFor(rows, accountId);
  observed.enrollmentPutCount = puts.length;
  assert.equal(puts.length, 1, 'carelog-be must receive exactly one enrollment PUT for the accountId');
  assert.equal(puts[0].status, 201, 'carelog-be must answer the enrollment PUT with 201');
  assert.ok(puts[0].te.toLowerCase().includes('chunked'), 'enrollment PUT must arrive with Transfer-Encoding: chunked');
  observed.enrollmentPut = 'exactly 1, status 201, Transfer-Encoding: chunked';

  stage = 'Carelog login through Gateway';
  const login = await send('POST', `${base}/api/v1/auth/login`, {
    body: { userId: carelog.userId, password: carelog.password },
  });
  expectStatus(login, 200, 'Carelog login through Gateway');
  assert.equal(typeof login.json?.data?.accessToken, 'string');
  assert.equal(jwtClaims(login.json.data.accessToken).sub, accountId, 'Carelog token sub must equal the accountId');
  observed.carelogLogin = 200;
  observed.carelogSubMatches = true;

  // Login reads claims from the real carelog-be (product-claims GET answered 200).
  stage = 'carelog-be claims read during login';
  rows = await waitForAccessLog((r) => claimsOkFor(r, accountId).length >= 1);
  observed.claimsGet200 = claimsOkFor(rows, accountId).length;
  assert.ok(observed.claimsGet200 >= 1, 'carelog-be claims GET must answer 200 during login');

  stage = 'Carelog wrong-password login through Gateway';
  const wrong = await send('POST', `${base}/api/v1/auth/login`, {
    body: { userId: carelog.userId, password: 'WrongPassword-9' },
  });
  expectStatus(wrong, 401, 'Carelog wrong-password login through Gateway');
  observed.carelogWrongPassword = 401;

  // Same Idempotency-Key and body: 201, no second enrollment PUT, no second carelog-be row.
  stage = 'Carelog registration replay through Gateway';
  const putsBefore = putsFor(await readAccessLog(), accountId).length;
  const replay = await send('POST', `${base}/api/v1/auth/carelog/registration`, {
    headers: { 'idempotency-key': idempotencyKey },
    body: carelog,
  });
  expectStatus(replay, 201, 'Carelog registration replay through Gateway');
  observed.replay = 201;
  const usersAfter = psql('carelog_be_e2e', `SELECT count(*) FROM users WHERE external_account_id = '${accountId}'`);
  observed.carelogUserRowsAfterReplay = Number(usersAfter[0][0]);
  assert.equal(observed.carelogUserRowsAfterReplay, 1, 'replay must not create a second carelog-be row');
  await new Promise((resolve) => setTimeout(resolve, 3000));
  observed.replayExtraPuts = putsFor(await readAccessLog(), accountId).length - putsBefore;
  assert.equal(observed.replayExtraPuts, 0, 'replay must not send another enrollment PUT');
}

async function financeSection(base) {
  const runId = randomBytes(6).toString('hex');
  const accounts = {
    A: { email: `dual-finance-a-${runId}@example.test`, password: 'FinanceDual-pass1' },
    B: { email: `dual-finance-b-${runId}@example.test`, password: 'FinanceDual-pass2' },
  };

  for (const [label, account] of Object.entries(accounts)) {
    stage = `Finance signup ${label} through Gateway`;
    const signup = await send('POST', `${base}/api/v1/auth/finance-reference/signup`, {
      body: { email: account.email, password: account.password },
    });
    expectStatus(signup, 201, `Finance signup ${label} through Gateway`);
    assert.match(signup.json?.data?.accountId ?? '', UUID_RE);
    account.accountId = signup.json.data.accountId;
  }
  assert.notEqual(accounts.A.accountId, accounts.B.accountId);
  observed.financeSignup = '201 / 201';

  for (const [label, account] of Object.entries(accounts)) {
    stage = `Finance login ${label} through Gateway`;
    const login = await send('POST', `${base}/api/v1/auth/finance-reference/login`, {
      body: { userId: account.email, password: account.password },
    });
    expectStatus(login, 200, `Finance login ${label} through Gateway`);
    assert.equal(login.json.data.tokenType, 'Bearer');
    const claims = jwtClaims(login.json.data.accessToken);
    assert.equal(claims.sub, account.accountId);
    assert.equal(claims.iss, FINANCE_ISSUER);
    account.token = login.json.data.accessToken;
  }
  observed.financeLogin = '200 / 200';

  const headers = (account) => ({ authorization: `Bearer ${account.token}` });
  const journal = {
    type: 'investment',
    assetName: 'Dual-product synthetic investment',
    occurredAt: '2026-11-18T09:31:00.000',
    timeZone: 'Asia/Seoul',
    action: 'interest',
    reasoning: 'Synthetic dual-product integration E2E; no product or customer data.',
  };

  stage = 'Finance journal create by A through Gateway';
  const created = await send('POST', `${base}/api/finance/journals`, {
    headers: { ...headers(accounts.A), 'idempotency-key': `dual-finance-${randomUUID()}` },
    body: journal,
  });
  expectStatus(created, 201, 'Finance journal create by A through Gateway');
  assert.match(created.json?.journalId ?? '', UUID_RE);
  const journalId = created.json.journalId;
  const location = created.headers.get('location') ?? '';
  assert.ok(location.endsWith(`/finance/journals/${journalId}`), 'Location must end with /finance/journals/<id>');
  observed.journalCreate = 201;

  stage = 'Finance journal detail re-read by A through Gateway';
  const detailA = await send('GET', `${base}/api/finance/journals/${journalId}`, { headers: headers(accounts.A) });
  expectStatus(detailA, 200, 'Finance journal detail re-read by A through Gateway');
  assert.equal(detailA.json.journalId, journalId);
  assert.equal(detailA.json.assetName, journal.assetName);
  assert.equal(detailA.json.action, journal.action);
  assert.equal(detailA.json.reasoning, journal.reasoning);
  assert.equal(detailA.json.occurredAt, journal.occurredAt);
  assert.equal(detailA.json.timeZone, journal.timeZone);
  assert.equal(detailA.json.revision, 0);
  observed.journalDetailA = 200;

  stage = 'Finance journal list re-read by A through Gateway';
  const listA = await send('GET', `${base}/api/finance/journals?limit=20`, { headers: headers(accounts.A) });
  expectStatus(listA, 200, 'Finance journal list re-read by A through Gateway');
  assert.ok(listA.json.items.some((item) => item.journalId === journalId), 'A list must contain the journal A created');
  observed.journalListA = 200;

  stage = 'Finance journal detail read by B through Gateway';
  const detailB = await send('GET', `${base}/api/finance/journals/${journalId}`, { headers: headers(accounts.B) });
  assert.ok([403, 404].includes(detailB.status), `B detail read expected 403 or 404, got ${detailB.status}`);
  assert.equal(JSON.stringify(detailB.json ?? {}).includes(journal.assetName), false, 'B detail must not leak content');
  observed.journalDetailB = detailB.status;

  stage = 'Finance journal list read by B through Gateway';
  const listB = await send('GET', `${base}/api/finance/journals?limit=20`, { headers: headers(accounts.B) });
  expectStatus(listB, 200, 'Finance journal list read by B through Gateway');
  assert.ok(!listB.json.items.some((item) => item.journalId === journalId), 'B list must not contain A journal');
  observed.journalListB = `200, ${listB.json.items.length} items, A journal excluded`;

  stage = 'Finance ownership database check';
  const ownership = psql('finance_db',
    `SELECT
       (SELECT count(*) FROM journals WHERE id = '${journalId}' AND identity_user_id = '${accounts.A.accountId}'),
       (SELECT count(*) FROM journals WHERE id = '${journalId}' AND identity_user_id <> '${accounts.A.accountId}')`);
  assert.deepEqual(ownership, [['1', '0']], 'journal must be owned by A only');
  observed.dbOwner = 'owner rows 1 (A), foreign rows 0';
}

async function main() {
  const base = process.env.E2E_GATEWAY_URL;
  const carelogBase = process.env.E2E_CARELOG_URL;
  assert.ok(base && carelogBase, 'gateway and carelog-be URLs are required');
  assert.equal(process.env.CARELOG_ENROLLMENT_TARGET, 'real', 'CARELOG_ENROLLMENT_TARGET must be real');

  stage = 'Carelog section';
  await carelogSection(base);
  stage = 'Finance section';
  await financeSection(base);

  const summary = [
    'Dev integration dual-product E2E: PASS (platform-core dual auth, gateway, real carelog-be prod profile, finance-harness-be)',
    'CARELOG_ENROLLMENT_TARGET=real',
    `carelog registration:201 core_operation:${observed.coreOperationState} carelog_be_manager_rows:${observed.carelogUserRows}`,
    `carelog enrollment PUT: ${observed.enrollmentPut}`,
    `carelog login:200 sub_matches_accountId:${observed.carelogSubMatches} claims_get_200:${observed.claimsGet200}`,
    `carelog wrong_password:${observed.carelogWrongPassword}`,
    `carelog replay_same_key: ${observed.replay} carelog_be_rows_after:${observed.carelogUserRowsAfterReplay} extra_enrollment_puts:${observed.replayExtraPuts}`,
    `finance signup A/B:${observed.financeSignup} login A/B:${observed.financeLogin}`,
    `finance journal create:${observed.journalCreate} detail_A:${observed.journalDetailA} list_A:${observed.journalListA}`,
    `finance detail_B:${observed.journalDetailB} (403 or 404, no leak) list_B: ${observed.journalListB}`,
    `finance db owner check: ${observed.dbOwner}`,
  ];
  console.log(summary.join('\n'));
  if (process.env.GITHUB_STEP_SUMMARY) {
    await appendFile(process.env.GITHUB_STEP_SUMMARY, ['', '### 검증 항목 (E2E, 보정 후 스택)', ...summary.map((l) => `- ${l}`), ''].join('\n'));
  }
}

main().catch((error) => {
  console.error(`Dev integration dual-product E2E: FAIL at stage "${stage}"`);
  if (process.env.E2E_DEBUG_ASSERTIONS === '1') {
    console.error(error?.message ?? error);
  }
  process.exitCode = 1;
});
